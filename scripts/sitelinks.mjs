import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { format } from 'prettier';
import { createSitelinkResolver } from '../src/sources/sitelinks.ts';
const expected = '20c8790ba758172196f7dc9c75fe34c70a2e26d191acd2e46c2caf7164c84bf1';
function notice(value) {
  return [
    'Wikidata sitelink facts — CC0-1.0. Wikidata contributors.',
    'https://www.wikidata.org/wiki/Wikidata:Licensing',
    'https://creativecommons.org/publicdomain/zero/1.0/',
    `Sitelink catalog ${value.version}; reviewed extract SHA-256 ${expected}.`,
    'Editorial extraction of structured sitelinks, not an original HTTP/API response.',
    'Only explicit QID/site/title/URL facts. No Wikipedia article text or Commons image.',
    ...value.snapshots.map(
      (s) => `${s.wikidataId} revision ${s.revision}; reviewed ${s.verifiedAt}; ${s.sourceUrl}`,
    ),
    '',
  ].join('\n');
}
export async function buildSitelinks(bytes) {
  if (bytes.length > 131072 || createHash('sha256').update(bytes).digest('hex') !== expected)
    throw new Error('SITELINK_REVIEW_CHECKSUM');
  const value = JSON.parse(bytes.toString('utf8'));
  if (Object.keys(value).sort().join(',') !== 'snapshots,version')
    throw new Error('SITELINK_MANIFEST');
  createSitelinkResolver(value.version, value.snapshots);
  return format(
    `// Generated by scripts/sitelinks.mjs. Review the pinned source before changing.\nexport const sitelinkManifest = ${JSON.stringify({ version: value.version, sha256: expected, bytes: bytes.length, licenseId: 'CC0-1.0', sourcePath: 'data/sitelinks/reviewed.json' })} as const;\nexport const sourceNotices = ${JSON.stringify(notice(value))};\nexport const reviewedSitelinks = ${JSON.stringify(value.snapshots)};\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  );
}
export async function prepareSitelinks(check = false) {
  const bytes = await readFile('data/sitelinks/reviewed.json');
  const output = await buildSitelinks(bytes);
  const path = 'src/sources/generated/sitelinks.ts';
  const noticePath = 'assets/licenses/Wikidata-sitelink-NOTICE.txt';
  const noticeText = notice(JSON.parse(bytes.toString('utf8')));
  if (check) {
    if ((await readFile(path, 'utf8')) !== output) throw new Error('SITELINK_GENERATED_STALE');
    if ((await readFile(noticePath, 'utf8')) !== noticeText)
      throw new Error('SITELINK_NOTICE_STALE');
  } else {
    await mkdir('src/sources/generated', { recursive: true });
    await writeFile(path, output);
    await writeFile(noticePath, noticeText);
  }
}
if (process.argv[1]?.endsWith('/scripts/sitelinks.mjs')) {
  await prepareSitelinks(process.argv.includes('--check'));
  process.stdout.write('Sitelinks: reviewed checksum, schema and generated snapshot PASS\n');
}
